"""Reading and writing ``devbox.lock``.

The written form is deterministic — keys sorted, no YAML anchors, no flow style,
LF line endings — so a re-resolution that changes nothing produces a byte
identical file and a zero-line diff in code review.
"""

from __future__ import annotations

from collections.abc import Mapping
from pathlib import Path

import yaml

from devbox.errors import LockfileError
from devbox.lockfile.models import LOCK_VERSION, LockedRuntime, Lockfile

__all__ = ["dump_lockfile", "parse_lockfile", "read_lockfile", "write_lockfile"]

_HEADER = (
    "# devbox.lock — generated by 'devbox install'. Commit this file.\n"
    "# It pins the exact runtime artifacts (and their SHA256) used by this project.\n"
)


def read_lockfile(path: Path) -> Lockfile:
    """Read and validate a lockfile.  A missing file yields an empty lockfile."""
    if not path.is_file():
        return Lockfile()
    try:
        text = path.read_text(encoding="utf-8-sig")
    except OSError as exc:
        msg = f"cannot read {path}: {exc}"
        raise LockfileError(msg) from exc
    return parse_lockfile(text, source=str(path))


def parse_lockfile(text: str, *, source: str = "devbox.lock") -> Lockfile:
    """Parse lockfile YAML into a validated :class:`Lockfile`."""
    try:
        document = yaml.safe_load(text)
    except yaml.YAMLError as exc:
        msg = f"{source}: invalid YAML: {exc}"
        raise LockfileError(msg, hint="Delete the file and run 'devbox install'.") from exc
    if document is None:
        return Lockfile()
    if not isinstance(document, Mapping):
        msg = f"{source}: the top level must be a mapping, got {type(document).__name__}"
        raise LockfileError(msg)

    raw_lock_version = document.get("lock_version", LOCK_VERSION)
    if isinstance(raw_lock_version, bool) or not isinstance(raw_lock_version, int):
        msg = f"{source}: 'lock_version' must be an integer, got {raw_lock_version!r}"
        raise LockfileError(msg)

    runtimes_document = document.get("runtimes") or {}
    if not isinstance(runtimes_document, Mapping):
        msg = f"{source}: 'runtimes' must be a mapping, got {type(runtimes_document).__name__}"
        raise LockfileError(msg)

    runtimes: dict[str, dict[str, LockedRuntime]] = {}
    for raw_name, versions in runtimes_document.items():
        name = str(raw_name)
        if not isinstance(versions, Mapping):
            msg = f"{source}: runtimes.{name} must be a mapping of version -> entry"
            raise LockfileError(msg)
        for raw_version, entry in versions.items():
            version = str(raw_version)
            if not isinstance(entry, Mapping):
                msg = f"{source}: runtimes.{name}.{version} must be a mapping"
                raise LockfileError(msg)
            runtimes.setdefault(name, {})[version] = _entry_from_document(
                name, version, entry, source
            )

    lock = Lockfile(lock_version=raw_lock_version, runtimes=runtimes)
    lock.validate()
    return lock


def _entry_from_document(
    name: str,
    version: str,
    entry: Mapping[str, object],
    source: str,
) -> LockedRuntime:
    def text_field(key: str, *, required: bool = False) -> str:
        value = entry.get(key)
        if value is None:
            if required:
                msg = f"{source}: runtimes.{name}.{version}.{key} is required"
                raise LockfileError(msg)
            return ""
        if isinstance(value, bool) or not isinstance(value, str | int | float):
            msg = f"{source}: runtimes.{name}.{version}.{key} must be a string"
            raise LockfileError(msg)
        return str(value)

    raw_size = entry.get("size", 0)
    if isinstance(raw_size, bool) or not isinstance(raw_size, int):
        msg = f"{source}: runtimes.{name}.{version}.size must be an integer"
        raise LockfileError(msg)

    return LockedRuntime(
        name=name,
        version=version,
        platform=text_field("platform", required=True),
        sha256=text_field("sha256", required=True).lower(),
        source=text_field("source"),
        url=text_field("url"),
        size=raw_size,
        archive=text_field("archive"),
    )


class _LockfileDumper(yaml.SafeDumper):
    """A dumper that quotes strings YAML would otherwise read back as a number.

    Version keys are the reason: unquoted, ``8.4`` round-trips as a float and
    ``24.60`` comes back as ``24.6``.  A lockfile that does not round-trip
    byte-for-byte is not a lockfile.
    """


def _represent_str(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    style = "'" if _is_ambiguous_scalar(value) else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


def _is_ambiguous_scalar(value: str) -> bool:
    try:
        return not isinstance(yaml.safe_load(value), str)
    except yaml.YAMLError:
        return True


_LockfileDumper.add_representer(str, _represent_str)


def dump_lockfile(lock: Lockfile) -> str:
    """Render a lockfile deterministically.

    Keys sorted, block style, no anchors, ambiguous scalars quoted: re-resolving
    a project that has not changed produces a byte-identical file.
    """
    body = yaml.dump(
        lock.to_document(),
        Dumper=_LockfileDumper,
        sort_keys=True,
        default_flow_style=False,
        allow_unicode=True,
        width=100,
    )
    return _HEADER + body


def write_lockfile(path: Path, lock: Lockfile) -> None:
    """Write *lock* to *path* atomically, with LF newlines on every platform."""
    lock.validate()
    text = dump_lockfile(lock)
    temporary = path.with_name(path.name + ".tmp")
    try:
        temporary.write_text(text, encoding="utf-8", newline="\n")
        temporary.replace(path)
    except OSError as exc:
        temporary.unlink(missing_ok=True)
        msg = f"cannot write {path}: {exc}"
        raise LockfileError(msg) from exc
