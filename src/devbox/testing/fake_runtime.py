"""Building fake runtimes and fake registries.

Everything Devbox does to a runtime — download, verify, extract, install, put on
a child's ``PATH``, execute — is exercised end to end against these, on a machine
with no Node, no PostgreSQL and no network access.  They are *not* mocks: the
files are real, the archives are real, the SHA256 digests are real, and the
processes started from them are real.

Shipped inside the package (rather than living only under ``tests/``) so that
``devbox test`` can build them, and so anyone can try Devbox on a machine with
nothing installed.
"""

from __future__ import annotations

import hashlib
import json
import stat
import zipfile
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from pathlib import Path

__all__ = [
    "FakeArtifact",
    "FakeRegistry",
    "build_fake_registry",
    "build_fake_runtime",
    "package_fake_runtime",
    "payload_source",
]

_POSIX_LAUNCHER = """#!/bin/sh
# Fake {name} {version} launcher generated by devbox.testing.fake_runtime.
# Resolves its own directory so the runtime works from any working directory.
DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
DEVBOX_FAKE_RUNTIME_VERSION="{version}" \\
DEVBOX_FAKE_RUNTIME_NAME="{name}" \\
exec "{python}" "$DIR/runtime_main.py" "$@"
"""

_WINDOWS_LAUNCHER = """@echo off
REM Fake {name} {version} launcher generated by devbox.testing.fake_runtime.
setlocal
set "DEVBOX_FAKE_RUNTIME_VERSION={version}"
set "DEVBOX_FAKE_RUNTIME_NAME={name}"
"{python}" "%~dp0runtime_main.py" %*
exit /b %ERRORLEVEL%
"""


def payload_source() -> str:
    """Source of the fake runtime payload.

    Read from the installed module file rather than embedded as a string so the
    payload stays a normal, linted, type-checked module with a single definition.
    """
    from devbox.testing import fake_runtime_main

    origin = getattr(fake_runtime_main, "__file__", None)
    if origin is None:  # pragma: no cover - only in an exotic frozen build
        msg = (
            "devbox.testing.fake_runtime_main has no source on disk; fake runtimes are a "
            "development facility and are not available from a frozen executable"
        )
        raise RuntimeError(msg)
    return Path(origin).read_text(encoding="utf-8")


def build_fake_runtime(
    destination: Path,
    *,
    name: str = "node",
    version: str = "0.0.0",
    python_executable: str | None = None,
    extra_executables: Sequence[str] = (),
) -> Path:
    """Materialise a runnable fake runtime at *destination*.

    Produces both launchers on every platform.  The Windows ``.cmd`` is written
    on Linux too: it is inert there, and generating it unconditionally keeps the
    archives byte-identical whatever machine built them.

    *extra_executables* creates additional launchers sharing the same payload —
    ``npm``, ``psql``, ``mysqladmin`` — which is how a fake runtime can stand in
    for a package manager or a database client.
    """
    import sys

    python = python_executable or sys.executable
    destination.mkdir(parents=True, exist_ok=True)
    (destination / "runtime_main.py").write_text(payload_source(), encoding="utf-8", newline="\n")

    for executable in (name, *extra_executables):
        posix_launcher = destination / executable
        posix_launcher.write_text(
            _POSIX_LAUNCHER.format(name=executable, version=version, python=python),
            encoding="utf-8",
            newline="\n",
        )
        posix_launcher.chmod(posix_launcher.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP)

        (destination / f"{executable}.cmd").write_text(
            _WINDOWS_LAUNCHER.format(name=executable, version=version, python=python),
            encoding="utf-8",
            newline="\r\n",
        )

    (destination / "VERSION").write_text(f"{version}\n", encoding="utf-8", newline="\n")
    return destination


@dataclass(frozen=True, slots=True)
class FakeArtifact:
    """A packaged fake runtime plus the digest a registry would advertise."""

    name: str
    version: str
    platform: str
    path: Path
    sha256: str
    size: int

    @property
    def relative_url(self) -> str:
        return f"{self.name}/{self.version}/{self.platform}.zip"


@dataclass(frozen=True, slots=True)
class FakeRegistry:
    """A filesystem registry root plus everything it publishes."""

    root: Path
    artifacts: tuple[FakeArtifact, ...]

    @property
    def index_path(self) -> Path:
        return self.root / "index.json"

    def artifact(self, name: str, version: str) -> FakeArtifact:
        for candidate in self.artifacts:
            if candidate.name == name and candidate.version == version:
                return candidate
        msg = f"fake registry does not publish {name} {version}"
        raise KeyError(msg)


def package_fake_runtime(
    source: Path,
    archive_path: Path,
    *,
    prefix: str = "",
) -> tuple[str, int]:
    """Zip a runtime tree deterministically and return ``(sha256, size)``.

    Entries are sorted and timestamps fixed, so the same tree always produces
    the same bytes and therefore the same digest — which is what lets the tests
    assert on integrity rather than on luck.
    """
    archive_path.parent.mkdir(parents=True, exist_ok=True)
    files = sorted(path for path in source.rglob("*") if path.is_file())
    with zipfile.ZipFile(archive_path, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for path in files:
            relative = path.relative_to(source).as_posix()
            arcname = f"{prefix}/{relative}" if prefix else relative
            info = zipfile.ZipInfo(arcname, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            mode = path.stat().st_mode
            info.external_attr = (mode & 0xFFFF) << 16
            archive.writestr(info, path.read_bytes())
    data = archive_path.read_bytes()
    return hashlib.sha256(data).hexdigest(), len(data)


def build_fake_registry(
    root: Path,
    runtimes: Iterable[tuple[str, str]],
    *,
    platform: str = "windows-x64",
    python_executable: str | None = None,
    extra_executables: Sequence[str] = (),
    prefix: str = "",
    corrupt: Iterable[tuple[str, str]] = (),
) -> FakeRegistry:
    """Build a complete filesystem registry publishing each ``(name, version)``.

    *corrupt* names entries whose advertised SHA256 is deliberately wrong, so a
    test can prove the install is refused.  The artifact itself stays valid; only
    the index lies, which is exactly the situation integrity checking exists for.
    """
    root.mkdir(parents=True, exist_ok=True)
    staging = root / ".staging"
    corrupt_keys = {(name, version) for name, version in corrupt}

    artifacts: list[FakeArtifact] = []
    index: dict[str, dict[str, dict[str, dict[str, object]]]] = {}

    for name, version in runtimes:
        tree = staging / name / version
        build_fake_runtime(
            tree,
            name=name,
            version=version,
            python_executable=python_executable,
            extra_executables=extra_executables,
        )
        archive_path = root / name / version / f"{platform}.zip"
        digest, size = package_fake_runtime(tree, archive_path, prefix=prefix)
        advertised = "0" * 64 if (name, version) in corrupt_keys else digest
        artifacts.append(
            FakeArtifact(
                name=name,
                version=version,
                platform=platform,
                path=archive_path,
                sha256=digest,
                size=size,
            )
        )
        index.setdefault(name, {}).setdefault(version, {})[platform] = {
            "url": f"{name}/{version}/{platform}.zip",
            "sha256": advertised,
            "size": size,
            "archive": f"{name}-{version}-{platform}.zip",
        }

    _remove_tree(staging)
    (root / "index.json").write_text(
        json.dumps({"schema": 1, "runtimes": index}, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    return FakeRegistry(root=root, artifacts=tuple(artifacts))


def _remove_tree(path: Path) -> None:
    import shutil

    shutil.rmtree(path, ignore_errors=True)
